import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { Store } from './store.js';
import { EventBus } from './events.js';
import type { Config } from '../types.js';

/**
 * Regression: the Inbox "Purge" (finished + older than N days) deleted the
 * phase tasks of goals that were still live. A goal's record points at those
 * tasks (phases[].taskIds) and its Judger minutes live in their artifacts dirs,
 * so purging them silently erased the goal's history — surfacing to the user as
 * "my Amazon ebook (goal-7f169be2) tasks are gone". A task generated by a goal
 * whose record still exists must survive the purge; once the goal itself is
 * deleted its tasks are fair game again.
 */
function makeStore(): { store: Store; goals: string } {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cowork-purge-goal-'));
  const paths = {
    inbox: path.join(root, 'inbox'),
    artifacts: path.join(root, 'artifacts'),
    inputs: path.join(root, 'inputs'),
    status: path.join(root, 'status'),
    decisions: path.join(root, 'decisions'),
    workflows: path.join(root, 'workflows'),
    goals: path.join(root, 'goals'),
    agencyAgents: path.join(root, 'agency-agents'),
  };
  for (const p of Object.values(paths)) fs.mkdirSync(p, { recursive: true });
  const config = { paths, orchestration: { brains: {} } } as unknown as Config;
  return { store: new Store(config, new EventBus()), goals: paths.goals };
}

/** Create a task and back-date it to "finished 60 days ago". */
function oldDoneTask(store: Store, title: string, context: Record<string, unknown> = {}) {
  const task = store.createTask({ title, from: { platform: 'p', agent: 'a' }, context } as any);
  const old = new Date(Date.now() - 60 * 86400000).toISOString();
  const t = store.getTask(task.id)!;
  Object.assign(t, { status: 'done', createdAt: old, completedAt: old });
  store.saveTask(t);
  return t;
}

test('purge keeps finished tasks that belong to a live goal', () => {
  const { store, goals } = makeStore();
  fs.writeFileSync(path.join(goals, 'goal-live.json'), JSON.stringify({ goalId: 'goal-live' }));

  const goalTask = oldDoneTask(store, 'KDP baseline snapshot', { goalId: 'goal-live', goalGenerated: true });
  const plain = oldDoneTask(store, 'one-off chore');

  const out = store.purgeTasks({ olderThanDays: 30 });

  assert.deepEqual(out.purged.map(p => p.id), [plain.id], 'only the goal-less task is purged');
  assert.ok(store.getTask(goalTask.id), 'the live goal\'s task survives');
});

test('purge still removes tasks of a goal that no longer exists', () => {
  const { store } = makeStore();
  const orphan = oldDoneTask(store, 'left behind by a deleted goal', { goalId: 'goal-gone', goalGenerated: true });

  const out = store.purgeTasks({ olderThanDays: 30 });

  assert.deepEqual(out.purged.map(p => p.id), [orphan.id]);
  assert.equal(store.getTask(orphan.id), null);
});
